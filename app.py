def enrich_fallback(seed, level):
    if level == 'בסיסי':
        return seed
    extra = ' קיימת לפחות סתירה נוספת בין גרסת הדמות לבין נתון מתועד, והיא אינה גלויה בתחילת התרגיל.'
    if level == 'מתקדם':
        extra += ' בנוסף קיימות כמה חלופות סבירות, מידע שמקבל משמעות אחרת לאחר הצלבה ואפשרות ששינוי במעמד של אחד המעורבים יהיה נדרש בהתאם למה שייחשף.'
    seed = dict(seed)
    seed['truth'] += extra
    seed['facts'] += extra
    return seed


