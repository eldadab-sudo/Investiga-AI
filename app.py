def resilient_generate_case(org, level='בינוני'):
    profile = server.ORG_PROFILES.get(org)
    if not profile:
        return None
    difficulty = DIFFICULTY.get(level, DIFFICULTY['בינוני'])
    shape = {'title':'','level':level,'org':org,'person':'','status':'','procedure':profile['kind'],'brief':'','legal':'','truth':'','facts':''}
    prompt = f'''צור תיק חקירה פיקטיבי וריאליסטי בעברית עבור {org}, ברמת {level}.
ייעוד: {profile['mandate']}
תחומים: {', '.join(profile.get('domains') or [])}.
רמת הקושי חייבת להיות מורגשת מאוד: {difficulty['rules']}

התיק חייב להתחיל מאירוע קונקרטי שמגיע בפועל לרשות חוקרת. כתוב חומר פתיחה ברור וקצר: מי פנה או מה דווח, מה קרה לכאורה, מועד ומקום כללי ומה ידוע כרגע. אל תגלה את הפתרון. החוקר צריך לגלות את התמונה, לזהות סתירות, לבחון חלופות ולסווג בעצמו את האירוע לפי העובדות.

מאחורי הקלעים קבע אמת מלאה וקבועה, ציר זמן, מעורבים, ראיות או מסמכים קיימים, סתירות והסברים חלופיים. בשדה facts כלול לפחות {difficulty['facts_min']} עובדות קונקרטיות קצרות. ה-brief יהיה 70–120 מילים בלבד. ה-legal יתאר בקצרה את מעמד האדם והמסגרת הכללית. אין לכלול מידע מסווג, פרטים גרפיים או הוראות לביצוע עבירה, התחמקות או שיבוש.

החזר JSON בלבד במבנה {json.dumps(shape,ensure_ascii=False)}.'''
    raw = server.ai([{'role':'system','content':prompt}],700,True)
    if raw:
        try:
            case = json.loads(raw)
            required = ['title','person','status','brief','legal','truth','facts']
            if all(isinstance(case.get(k),str) and case[k].strip() for k in required):
                case['org'] = org
                case['level'] = level
                case['procedure'] = profile['kind']
                return case
        except Exception as exc:
            print('GEN CASE PARSE',repr(exc))
    print('GEN CASE FAST FALLBACK',org,level)
    return fallback_case(org,level,profile)


