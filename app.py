def resilient_generate_case(org, level='בינוני'):
    profile = server.ORG_PROFILES.get(org)
    if not profile:
        return None
    shape = {'title':'','level':level,'org':org,'person':'','status':'','procedure':profile['kind'],'brief':'','legal':'','truth':'','facts':''}
    prompt = f'''צור תיק חקירה פיקטיבי וריאליסטי בעברית עבור {org}, ברמת {level}.
ייעוד: {profile['mandate']}
בסיס משפטי ציבורי: {profile['legal_basis']}
תחומים מותרים: {', '.join(profile.get('domains') or [])}.

התיק חייב להיראות כמו אירוע אמיתי שמגיע לרשות חוקרת, ולא כמו תרגיל מופשט. התחל באירוע קונקרטי: מי פנה או מה דווח, מה קרה לכאורה, מועד ומקום כללי, ומה ידוע לחוקר ברגע פתיחת התיק. דוגמאות לסגנון במשטרה: אזרח מתלונן על עסקאות לא מוכרות בכרטיס האשראי; בעל עסק מתלונן על התפרצות וגניבת סחורה. אלה דוגמאות לסגנון בלבד — גוון תיקים מגוונים בהתאם לסמכות הארגון.

אל תגלה לחוקר את הפתרון. על החוקר לגלות את התמונה באמצעות שאלות. עליו לזהות בעצמו את סוג האירוע והסיווג המשפטי האפשרי לפי העובדות שמתפתחות. קבע מאחורי הקלעים אמת מלאה וקבועה, ציר זמן, אנשים, קשרים, מסמכים/ראיות קיימות, סתירות והסברים חלופיים. בשדה facts כתוב לפחות 10 עובדות קונקרטיות שהדמות יכולה לחשוף בהדרגה. ברמה מתקדמת הוסף סתירה משמעותית או חלופה סבירה שאינה גלויה בפתיחה.

ה-brief הוא חומר הפתיחה בלבד, בשפה פשוטה וברורה, 80–160 מילים. הוא לא יכלול את האמת הנסתרת ולא יאמר לחוקר מה המסקנה. ה-truth וה-facts מיועדים למנוע בלבד. ה-legal יתאר את מעמד האדם ואת המסגרת הכללית בלי להמציא סמכויות. אין לכלול פרטים גרפיים, מידע מסווג, הוראות לביצוע עבירה, התחמקות או שיבוש.

החזר JSON בלבד בדיוק במבנה {json.dumps(shape,ensure_ascii=False)}.'''
    for attempt in range(2):
        raw = server.ai([{'role':'system','content':prompt}],1400,True)
        if raw:
            try:
                case=json.loads(raw)
                required=['title','person','status','brief','legal','truth','facts']
                if all(isinstance(case.get(k),str) and case[k].strip() for k in required) and len(case['brief']) >= 180 and len(case['facts']) >= 250:
                    case['org']=org; case['level']=level; case['procedure']=profile['kind']
                    return case
            except Exception as exc:
                print('GEN CASE PARSE',attempt,repr(exc))
        prompt += '\nהגרסה הקודמת לא הייתה מפורטת מספיק. החזר תיק קונקרטי, מלא ותקין ב-JSON בלבד.'
    print('GEN CASE FALLBACK',org,level)
    return fallback_case(org,level,profile)


